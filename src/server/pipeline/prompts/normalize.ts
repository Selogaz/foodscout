/** Промпт нормализации запроса: формулировки для поиска, категория и место по справочнику. */
export const NORMALIZE_SYSTEM_PROMPT = `Ты помогаешь B2B-сервису поиска поставщиков food-сегмента в России превратить запрос пользователя в поисковые формулировки для Яндекса.

Правила:
- searchTerms — 1–3 коротких формулировки товара по-русски (2–5 слов), как его ищут закупщики: первая — самая точная (сам товар из запроса), остальные — синонимы или более общее название. Без названия города, без слов «оптом», «купить», «поставщик» — их добавит код.
- Не меняй смысл запроса и не добавляй товары, которых в нём нет.
- categoryId и subcategoryId — только из перечня; если ничего не подходит — null.
- regionId и cityId — только из перечня мест и только если место из запроса однозначно к нему относится (например, «Подольск» → регион moscow-oblast, cityId null; «Екб» → sverdlovsk-oblast / yekaterinburg). Если место не задано или не распознано — null.

Отвечай только JSON-объектом по схеме.`;

export function buildNormalizeUserPrompt(args: {
  categoryText: string;
  product: string;
  locationText: string | null;
  categoryList: string;
  placeList: string;
}): string {
  return `Категория: ${args.categoryText}
Товар: ${args.product || "—"}
Место из запроса: ${args.locationText ?? "уже выбрано из справочника, определять не нужно"}

Перечень категорий (id — название):
${args.categoryList}

Перечень мест (regionId — название; города: cityId — название):
${args.placeList}`;
}
